export type Settings = {
  apiKey: string;
  model: string;
  baseUrl: string;
  demoMode: boolean;
  name: string;
};

const KEY = "wpa-settings";
export const defaultSettings: Settings = {
  apiKey: "",
  model: "gpt-4o-mini",
  baseUrl: "https://api.openai.com/v1",
  demoMode: true,
  name: "",
};

export function loadSettings(): Settings {
  if (typeof window === "undefined") return defaultSettings;
  try {
    return { ...defaultSettings, ...JSON.parse(localStorage.getItem(KEY) || "{}") };
  } catch {
    return defaultSettings;
  }
}

export function saveSettings(s: Settings) {
  localStorage.setItem(KEY, JSON.stringify(s));
}

export function loadItem(key: string, fallback = "") {
  if (typeof window === "undefined") return fallback;
  return localStorage.getItem(key) ?? fallback;
}
export function saveItem(key: string, value: string) {
  localStorage.setItem(key, value);
}

export const DEMO_BANNER =
  "[DEMO MODE — sample text, not generated by AI. Add your API key in Settings for real results.]\n\n";

/** Calls an OpenAI-compatible chat completions API with the user's own key. */
export async function generate(system: string, user: string, demo: string): Promise<string> {
  const s = loadSettings();
  if (s.demoMode || !s.apiKey) return DEMO_BANNER + demo;
  const res = await fetch(`${s.baseUrl.replace(/\/$/, "")}/chat/completions`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${s.apiKey}` },
    body: JSON.stringify({
      model: s.model,
      messages: [
        { role: "system", content: system },
        { role: "user", content: user },
      ],
    }),
  });
  if (!res.ok) {
    const t = await res.text();
    throw new Error(`AI request failed (${res.status}): ${t.slice(0, 200)}`);
  }
  const j = await res.json();
  return j.choices?.[0]?.message?.content?.trim() || "No response returned.";
}
